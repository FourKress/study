export function toConfig(level: Level, seconds = level.seconds): QuizConfig {
  return {
    ops: level.ops,
    max: level.max,
    factorMin: level.factorMin,
    factorMax: level.factorMax,
    otherMin: level.otherMin,
    otherMax: level.otherMax,
    count: level.count,
    seconds,
  };
}

export function isUnlocked(index: number, clears: Record<string, { stars: number }>) {
  if (index <= 0) return true;
  return Boolean(clears[levels[index - 1].id]);
}
